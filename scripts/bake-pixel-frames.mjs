import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

const root = process.cwd(), require = createRequire(import.meta.url);
const ts = require(resolve(root, 'apps/mobile/node_modules/typescript'));
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(readFileSync(filename, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }, fileName: filename,
}).outputText, filename);
const source = resolve(root, 'scripts/pixel-frames');
const { tracedPixelFrames, tracedCoatMasks } = require(`${source}/pixelFrames.generated.ts`);
const { pixelFrameOverrides, dogPixelFrames, otherPixelFrame } = require(`${source}/pixelFrames.overrides.ts`);
const cats = tracedPixelFrames.map(frame => pixelFrameOverrides[`${frame.pose}:${frame.index}`] ?? frame);
const frames = (name, items) => `export const ${name}: readonly PixelFrame[] = [\n${items.map(frame => JSON.stringify(frame)).join(',\n')}\n];\n`;
const baked = '// Generated by node scripts/bake-pixel-frames.mjs. Do not edit.\n'
  + "import type { PixelFrame } from './pixelFrames';\n"
  + frames('catPixelFrames', cats) + frames('dogPixelFrames', dogPixelFrames)
  + `export const otherPixelFrame: PixelFrame = ${JSON.stringify(otherPixelFrame)};\n`
  + `export const tracedCoatMasks = ${JSON.stringify(tracedCoatMasks)} as const;\n`;
const target = resolve(root, 'apps/mobile/src/contexts/avatar/domain/pixelFrames.baked.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== baked) {
    console.error('Pixel frame bake is stale. Run node scripts/bake-pixel-frames.mjs.');
    process.exitCode = 1;
  } else console.log('Pixel frame bake matches the source pipeline.');
} else {
  writeFileSync(target, baked);
  console.log(`Baked ${cats.length} cat + ${dogPixelFrames.length} dog + 1 other frame and 8 coat masks.`);
}
